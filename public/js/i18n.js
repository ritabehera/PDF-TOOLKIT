class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('pdf_lang') || 'en';
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  setLanguage(langKey) {
    if (!i18nTranslations[langKey]) return;
    this.currentLang = langKey;
    localStorage.setItem('pdf_lang', langKey);
    this.applyLanguage(langKey);
    if (typeof showToast === 'function') {
      const langNames = { en: 'English', hi: 'हिंदी (Hindi)', or: 'ଓଡ଼ିଆ (Odia)' };
      showToast(`Language set to ${langNames[langKey]}`, 'success');
    }
  }

  t(key) {
    const dict = i18nTranslations[this.currentLang] || i18nTranslations.en;
    return dict[key] || i18nTranslations.en[key] || key;
  }

  applyLanguage(langKey) {
    const dict = i18nTranslations[langKey] || i18nTranslations.en;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' && el.type === 'text') {
          el.placeholder = dict[key];
        } else {
          // Preserve child icons if present
          const icon = el.querySelector('i');
          if (icon) {
            el.innerHTML = '';
            el.appendChild(icon);
            el.appendChild(document.createTextNode(' ' + dict[key]));
          } else {
            el.textContent = dict[key];
          }
        }
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    const selector = document.getElementById('languageSelect');
    if (selector) selector.value = langKey;
  }
}

window.I18n = new I18nEngine();

document.addEventListener('DOMContentLoaded', () => {
  window.I18n.init();
});
